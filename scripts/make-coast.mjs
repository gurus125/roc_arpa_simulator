// Makes src/engine/real-coasts.ts: a real coastline for a scenario, from open data.
//
//   npm install @geo-maps/earth-coastlines-250m     (in any folder; about 19 MB; not needed to build or run the simulator)
//   node scripts/make-coast.mjs path/to/node_modules/@geo-maps/earth-coastlines-250m/map.geo.json
//
// Data: geo-maps "earth-coastlines-250m" (github.com/simonepri/geo-maps), made from OpenStreetMap.
// (c) OpenStreetMap contributors, Open Database License (ODbL) 1.0. Stated accuracy: 250 m.
// The coastline written by this script is an extract of that database and stays under the ODbL.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { AREAS, toLocal } from "./areas.mjs";

const TOLERANCE_NM = 0.03; // points nearer than this to the simplified line are left out
const MIN_LENGTH_NM = 0.3; // shorter pieces (rocks, pond edges) are left out

const src = process.argv[2];
if (!src) {
  console.error("Give the path of map.geo.json (see the top of this file).");
  process.exit(1);
}
const geo = JSON.parse(readFileSync(src, "utf8"));
const polygons = geo.geometries.flatMap((g) => (g.type === "MultiPolygon" ? g.coordinates : [g.coordinates]));

const inside = (b, [lon, lat]) => lat >= b.south && lat <= b.north && lon >= b.west && lon <= b.east;
/** Where the segment p -> q leaves or enters the box (p inside, q outside, or the other way round). */
function crossing(b, p, q) {
  let lo = 0, hi = 1;
  const at = (k) => [p[0] + (q[0] - p[0]) * k, p[1] + (q[1] - p[1]) * k];
  const pin = inside(b, p);
  for (let i = 0; i < 30; i++) {
    const mid = (lo + hi) / 2;
    if (inside(b, at(mid)) === pin) lo = mid;
    else hi = mid;
  }
  return at(pin ? lo : hi);
}
function simplify(pts, tol) {
  if (pts.length <= 2) return pts;
  const [a, b] = [pts[0], pts[pts.length - 1]];
  const len = Math.hypot(b.e - a.e, b.n - a.n);
  let worst = 0, at = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const p = pts[i];
    const d = len === 0 ? Math.hypot(p.e - a.e, p.n - a.n) : Math.abs((b.e - a.e) * (a.n - p.n) - (a.e - p.e) * (b.n - a.n)) / len;
    if (d > worst) [worst, at] = [d, i];
  }
  if (worst <= tol) return [a, b];
  return [...simplify(pts.slice(0, at + 1), tol).slice(0, -1), ...simplify(pts.slice(at), tol)];
}
const lengthOf = (pts) => pts.slice(1).reduce((s, p, i) => s + Math.hypot(p.e - pts[i].e, p.n - pts[i].n), 0);

let out = `// GENERATED by scripts/make-coast.mjs. Do not edit by hand.
// Real coastlines, cut from the geo-maps "earth-coastlines-250m" data set, which is made from OpenStreetMap.
// (c) OpenStreetMap contributors. This data is under the Open Database License (ODbL) 1.0:
// https://opendatacommons.org/licenses/odbl/1.0/ . Stated accuracy about 250 m; coordinates rounded to 0.001 NM.
// A coastline only: no depths, lights, buoys or heights. It is not a chart and not for navigation.
import { Coast } from "./types";

`;
for (const area of AREAS) {
  const runs = [];
  for (const poly of polygons) {
    for (const ring of poly) {
      let minLon = 999, maxLon = -999, minLat = 999, maxLat = -999;
      for (const [lon, lat] of ring) {
        if (lon < minLon) minLon = lon;
        if (lon > maxLon) maxLon = lon;
        if (lat < minLat) minLat = lat;
        if (lat > maxLat) maxLat = lat;
      }
      const b = area.box;
      if (maxLon < b.west || minLon > b.east || maxLat < b.south || minLat > b.north) continue;
      let run = [];
      for (let i = 0; i < ring.length; i++) {
        const p = ring[i];
        const prev = i > 0 ? ring[i - 1] : null;
        if (inside(b, p)) {
          if (prev && !inside(b, prev)) run.push(crossing(b, prev, p));
          run.push(p);
        } else if (run.length > 0) {
          if (prev) run.push(crossing(b, prev, p));
          runs.push(run);
          run = [];
        }
      }
      if (run.length > 0) runs.push(run);
    }
  }
  const lines = runs
    .map((r) => simplify(r.map(([lon, lat]) => toLocal(area.origin, lat, lon)), TOLERANCE_NM))
    .filter((r) => r.length >= 2 && lengthOf(r) >= MIN_LENGTH_NM)
    .sort((a, b) => lengthOf(b) - lengthOf(a));
  const points = lines.reduce((s, l) => s + l.length, 0);
  const total = lines.reduce((s, l) => s + lengthOf(l), 0);
  console.log(`${area.title}: ${lines.length} pieces of coast, ${points} points, ${total.toFixed(0)} NM of coastline`);
  out += `/** ${area.title}: box ${area.box.south} to ${area.box.north} N, ${area.box.west} to ${area.box.east} E; ${lines.length} pieces, ${points} points, ${total.toFixed(0)} NM of coastline. */\n`;
  out += `export const ${area.id}_ORIGIN = { lat: ${area.origin.lat}, lon: ${area.origin.lon} };\n`;
  out += `export const ${area.id}_BOX = ${JSON.stringify(area.box)};\n`;
  out += `const ${area.id}_LINES: number[][] = [\n${lines.map((l) => `  [${l.map((p) => `${+p.e.toFixed(3)},${+p.n.toFixed(3)}`).join(",")}],`).join("\n")}\n];\n`;
  out += `export const ${area.id}_COAST: Coast[] = ${area.id}_LINES.map((l, i) => ({\n  name: \`${area.title} ${"${i + 1}"}\`,\n  closed: false,\n  points: Array.from({ length: l.length / 2 }, (_, k) => ({ e: l[2 * k]!, n: l[2 * k + 1]! })),\n}));\n`;
}
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "engine", "real-coasts.ts");
writeFileSync(target, out);
console.log(`Written ${target} (${(out.length / 1024).toFixed(0)} KB)`);
