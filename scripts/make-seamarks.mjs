// Makes src/engine/real-seamarks.ts: the buoys, beacons and lights of the real areas.
//
// Needs, once (not needed to build or run the simulator): the sea marks of the areas from
// OpenStreetMap. On https://overpass-turbo.eu run this query, then Export > "raw OSM data" (or
// GeoJSON) and save the file:
//
//   [out:json][timeout:120];
//   ( nwr["seamark:type"](18.45,72.3,19.35,73.1);
//     nwr["seamark:type"](15.0,73.35,15.8,74.15);
//     nwr["seamark:type"](9.55,75.75,10.35,76.55);
//     nwr["seamark:type"](22.35,69.2,23.2,70.45); );
//   out center tags;
//
// Then:   node scripts/make-seamarks.mjs <saved file> [output file, default src/engine/real-seamarks.ts]
// Keep the saved file out of the repository (it is only the input).
//
// Data (c) OpenStreetMap contributors, Open Database License (ODbL) 1.0: the same licence as the
// coastlines. As mapped by volunteers: some marks are missing and some may have been moved or
// changed since. NOT A CHART AND NOT FOR NAVIGATION.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { build } from "esbuild";
import { AREAS, toLocal } from "./areas.mjs";

const [file, outFile] = process.argv.slice(2);
if (!file) {
  console.error("Give the file saved from overpass-turbo (see the top of this file).");
  process.exit(1);
}
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
// The reading of the tags is the simulator's own (src/engine/seamarks.ts), so it is tested with the rest.
const bundled = await build({ entryPoints: [path.join(root, "src", "engine", "seamarks.ts")], bundle: true, format: "esm", platform: "node", write: false });
const { seaMarkFromTags } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString("base64")}`);

/** Every tagged object of the file as { lat, lon, tags }: raw Overpass JSON (nodes, or ways and relations with "center") or GeoJSON. */
function readObjects(text) {
  const j = JSON.parse(text);
  if (Array.isArray(j.elements)) {
    return j.elements
      .map((e) => ({ lat: e.lat ?? e.center?.lat, lon: e.lon ?? e.center?.lon, tags: e.tags ?? {} }))
      .filter((o) => Number.isFinite(o.lat) && Number.isFinite(o.lon));
  }
  if (Array.isArray(j.features)) {
    return j.features.flatMap((f) => {
      const g = f.geometry;
      const tags = { ...(f.properties?.tags ?? {}), ...Object.fromEntries(Object.entries(f.properties ?? {}).filter(([, v]) => typeof v === "string")) };
      if (g?.type === "Point") return [{ lat: g.coordinates[1], lon: g.coordinates[0], tags }];
      // A way or area: the middle of its points.
      const pts = g?.type === "LineString" ? g.coordinates : g?.type === "Polygon" ? g.coordinates[0] : [];
      if (!pts.length) return [];
      return [{ lat: pts.reduce((s, p) => s + p[1], 0) / pts.length, lon: pts.reduce((s, p) => s + p[0], 0) / pts.length, tags }];
    });
  }
  throw new Error("Not a file saved from overpass-turbo: expected raw OSM JSON (elements) or GeoJSON (features).");
}

const objects = readObjects(readFileSync(file, "utf8"));
const byArea = Object.fromEntries(AREAS.map((a) => [a.id.toLowerCase(), []]));
let skipped = 0;
for (const o of objects) {
  const area = AREAS.find((a) => o.lat >= a.box.south && o.lat <= a.box.north && o.lon >= a.box.west && o.lon <= a.box.east);
  if (!area) continue;
  const p = toLocal(area.origin, o.lat, o.lon);
  const m = seaMarkFromTags(o.tags, { e: +p.e.toFixed(4), n: +p.n.toFixed(4) });
  if (!m) {
    skipped++;
    continue;
  }
  const list = byArea[area.id.toLowerCase()];
  // The same mark mapped twice (a node and a way, say): kept once.
  if (list.some((x) => x.shape === m.shape && x.category === m.category && Math.hypot(x.pos.e - m.pos.e, x.pos.n - m.pos.n) < 0.02)) continue;
  list.push(m);
}

let out = `// GENERATED by scripts/make-seamarks.mjs. Do not edit by hand.
// Buoys, beacons and lights: (c) OpenStreetMap contributors, Open Database License (ODbL) 1.0, as
// mapped there (some missing, some possibly moved or changed since). NOT A CHART AND NOT FOR NAVIGATION.
import { SeaMark } from "./seamarks";

export const REAL_SEAMARKS_CREDIT =
  "Buoys, beacons and lights: © OpenStreetMap contributors (ODbL), as mapped there: some are missing and some may have changed. Not a chart and not for navigation.";

export const REAL_SEAMARKS: Record<string, SeaMark[]> = {
`;
for (const area of AREAS) {
  const id = area.id.toLowerCase();
  const list = byArea[id].sort((a, b) => b.pos.n - a.pos.n || a.pos.e - b.pos.e);
  const count = (s) => list.filter((m) => m.shape === s).length;
  console.log(`${area.title}: ${count("buoy")} buoys, ${count("beacon")} beacons, ${count("light")} lights, ${count("light-vessel")} light vessels, ${list.filter((m) => m.racon).length} racons`);
  out += `  /** ${area.title}: ${list.length} sea marks. */\n  ${id}: [\n`;
  for (const m of list) out += `    ${JSON.stringify(m)},\n`;
  out += "  ],\n";
}
out += "};\n";
const target = outFile ? path.resolve(outFile) : path.join(root, "src", "engine", "real-seamarks.ts");
writeFileSync(target, out);
console.log(`${objects.length} objects read, ${skipped} of other kinds left out. Written ${target} (${(out.length / 1024).toFixed(0)} KB)`);
