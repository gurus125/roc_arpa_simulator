// Makes src/engine/real-terrain.ts: ground heights and land masks for the real areas.
//
// Needs, once (neither is needed to build or run the simulator):
//   1. The Copernicus DEM GLO-90 tiles of the areas, in one folder (see TILES below; the download
//      command is in docs/INSTRUCTOR-MANUAL.md). Tiles that are all sea do not exist; that is fine.
//   2. npm install --no-save geotiff @geo-maps/earth-coastlines-250m     (in any folder)
// Then:
//   node scripts/make-terrain.mjs <folder of tiles> <path to @geo-maps/earth-coastlines-250m/map.geo.json> [path to the geotiff package]
//
// Heights: Copernicus DEM GLO-90 (a surface model: it includes buildings and trees, as a radar sees
// them). (c) DLR e.V. 2010-2014 and (c) Airbus Defence and Space GmbH 2014-2018, provided under
// COPERNICUS by the European Union and ESA; all rights reserved. Free to use, also commercially,
// with this credit.
// Land and water: from the geo-maps "earth-coastlines-250m" data set, made from OpenStreetMap,
// (c) OpenStreetMap contributors, Open Database License (ODbL) 1.0. The same data as the coastlines.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import { build } from "esbuild";
import { AREAS, toLocal, toLatLon } from "./areas.mjs";

/** Spacing of the height nodes, NM, and how many mask cells there are along each side of a height cell. */
const CELL_NM = 0.1;
const MASK_SCALE = 2;

const [tilesDir, geoPath, geotiffPath] = process.argv.slice(2);
if (!tilesDir || !geoPath) {
  console.error("Give the folder of tiles and the path of map.geo.json (see the top of this file).");
  process.exit(1);
}
const { fromFile } = await import(geotiffPath ? pathToFileURL(path.resolve(geotiffPath, "dist-module", "geotiff.js")).href : "geotiff");
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
// The packing is the simulator's own (src/engine/terrain.ts), so the two cannot drift apart.
const bundled = await build({ entryPoints: [path.join(root, "src", "engine", "terrain.ts")], bundle: true, format: "esm", platform: "node", write: false });
const { packTerrain, unpackTerrain } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString("base64")}`);

const tileName = (lat, lon) => `Copernicus_DSM_COG_30_N${String(lat).padStart(2, "0")}_00_E${String(lon).padStart(3, "0")}_00_DEM.tif`;
const tileCache = new Map();
/** One 1-degree tile: 1200 x 1200 heights, rows from the north, pixels covering the whole degree. Null if the file is not there (all sea). */
async function tile(lat, lon) {
  const key = `${lat},${lon}`;
  if (tileCache.has(key)) return tileCache.get(key);
  const f = path.join(tilesDir, tileName(lat, lon));
  let t = null;
  if (existsSync(f)) {
    const img = await (await fromFile(f)).getImage();
    const [data] = await img.readRasters();
    const [west, south, east, north] = img.getBoundingBox();
    t = { data, w: img.getWidth(), h: img.getHeight(), west, south, east, north };
  }
  tileCache.set(key, t);
  return t;
}
/** Highest DEM height inside the box lat0..lat1, lon0..lon1 (pixel centres), metres; null if no tile covers it. */
async function maxHeight(lat0, lat1, lon0, lon1) {
  let best = null;
  for (let la = Math.floor(lat0); la <= Math.floor(lat1); la++) {
    for (let lo = Math.floor(lon0); lo <= Math.floor(lon1); lo++) {
      const t = await tile(la, lo);
      if (!t) continue;
      const px = (lon) => (lon - t.west) / ((t.east - t.west) / t.w) - 0.5;
      const py = (lat) => (t.north - lat) / ((t.north - t.south) / t.h) - 0.5;
      const x0 = Math.max(0, Math.ceil(px(lon0))), x1 = Math.min(t.w - 1, Math.floor(px(lon1)));
      const y0 = Math.max(0, Math.ceil(py(lat1))), y1 = Math.min(t.h - 1, Math.floor(py(lat0)));
      // A footprint smaller than a pixel: the nearest pixel.
      const xs = x1 >= x0 ? [x0, x1] : [Math.round(px((lon0 + lon1) / 2)), Math.round(px((lon0 + lon1) / 2))];
      const ys = y1 >= y0 ? [y0, y1] : [Math.round(py((lat0 + lat1) / 2)), Math.round(py((lat0 + lat1) / 2))];
      for (let y = Math.max(0, ys[0]); y <= Math.min(t.h - 1, ys[1]); y++) {
        for (let x = Math.max(0, xs[0]); x <= Math.min(t.w - 1, xs[1]); x++) {
          const v = t.data[y * t.w + x];
          if (Number.isFinite(v) && (best === null || v > best)) best = v;
        }
      }
    }
  }
  return best;
}

const geo = JSON.parse(readFileSync(geoPath, "utf8"));
const rings = geo.geometries.flatMap((g) => (g.type === "MultiPolygon" ? g.coordinates : [g.coordinates])).flat();

let out = `// GENERATED by scripts/make-terrain.mjs. Do not edit by hand.
// Ground heights: Copernicus DEM GLO-90, (c) DLR e.V. 2010-2014 and (c) Airbus Defence and Space GmbH
// 2014-2018, provided under COPERNICUS by the European Union and ESA; all rights reserved. A surface
// model: buildings and trees are in the heights. Resampled here to the highest ground in each cell.
// Land and water: from OpenStreetMap data, (c) OpenStreetMap contributors, Open Database License (ODbL) 1.0.
// Not a chart and not for navigation.
import { PackedTerrain } from "./terrain";

export const REAL_TERRAIN_CREDIT =
  "Land heights: Copernicus DEM GLO-90, © DLR e.V. 2010-2014 and © Airbus Defence and Space GmbH 2014-2018, provided under COPERNICUS by the European Union and ESA; all rights reserved. Coastlines: © OpenStreetMap contributors (ODbL).";

export const REAL_TERRAIN: Record<string, PackedTerrain> = {
`;
for (const area of AREAS) {
  const o = area.origin;
  const b = area.box;
  const corners = [[b.south, b.west], [b.south, b.east], [b.north, b.west], [b.north, b.east]].map(([la, lo]) => toLocal(o, la, lo));
  const e0 = Math.min(...corners.map((c) => c.e));
  const e1 = Math.max(...corners.map((c) => c.e));
  const n0 = (b.south - o.lat) * 60;
  const n1 = (b.north - o.lat) * 60;
  const cols = Math.floor((e1 - e0) / CELL_NM) + 1;
  const rows = Math.floor((n1 - n0) / CELL_NM) + 1;

  // Heights at the nodes: the highest ground within half a cell of each.
  const heights = new Float32Array(cols * rows);
  let missing = 0;
  for (let j = 0; j < rows; j++) {
    for (let i = 0; i < cols; i++) {
      const e = e0 + i * CELL_NM;
      const n = n0 + j * CELL_NM;
      const lo = toLatLon(o, e - CELL_NM / 2, n - CELL_NM / 2);
      const hi = toLatLon(o, e + CELL_NM / 2, n + CELL_NM / 2);
      const h = await maxHeight(lo.lat, hi.lat, lo.lon, hi.lon);
      if (h === null) missing++;
      heights[j * cols + i] = Math.max(0, h ?? 0);
    }
  }

  // Land mask: even-odd rule against the land polygons, row by row.
  const mcols = (cols - 1) * MASK_SCALE;
  const mrows = (rows - 1) * MASK_SCALE;
  const mc = CELL_NM / MASK_SCALE;
  const edges = [];
  for (const ring of rings) {
    for (let k = 0; k + 1 < ring.length; k++) {
      const [x1, y1] = ring[k];
      const [x2, y2] = ring[k + 1];
      if (Math.max(y1, y2) < b.south - 0.01 || Math.min(y1, y2) > b.north + 0.01) continue;
      if (Math.min(x1, x2) > b.east + 0.5) continue; // only crossings to the west of a point count
      edges.push([x1, y1, x2, y2]);
    }
  }
  const mask = new Uint8Array(mcols * mrows);
  let land = 0;
  for (let j = 0; j < mrows; j++) {
    const n = n0 + (j + 0.5) * mc;
    const lat = o.lat + n / 60;
    const xs = [];
    for (const [x1, y1, x2, y2] of edges) {
      if ((y1 > lat) !== (y2 > lat)) xs.push(x1 + ((lat - y1) * (x2 - x1)) / (y2 - y1));
    }
    xs.sort((a, c) => a - c);
    let k = 0;
    for (let i = 0; i < mcols; i++) {
      const lon = toLatLon(o, e0 + (i + 0.5) * mc, n).lon;
      while (k < xs.length && xs[k] < lon) k++;
      if (k % 2 === 1) {
        mask[j * mcols + i] = 1;
        land++;
      }
    }
  }

  const grid = { e0, n0, cellNm: CELL_NM, cols, rows, heights, mask, maskScale: MASK_SCALE };
  const packed = packTerrain(grid);
  // Check: what is unpacked is what was packed.
  const back = unpackTerrain(packed);
  for (let q = 0; q < heights.length; q++) if (back.heights[q] !== Math.min(8191, Math.round(heights[q]))) throw new Error(`height ${q} did not survive packing`);
  for (let q = 0; q < mask.length; q++) if (back.mask[q] !== mask[q]) throw new Error(`mask ${q} did not survive packing`);
  let top = 0;
  for (const v of heights) top = Math.max(top, v);
  const size = (packed.h.length + packed.m.length) / 1024;
  console.log(`${area.title}: ${cols} x ${rows} heights (${missing} with no tile), highest ${top.toFixed(0)} m, ${((100 * land) / mask.length).toFixed(0)}% land, ${size.toFixed(0)} KB packed`);
  out += `  /** ${area.title}: ${cols} x ${rows} heights every ${CELL_NM} NM, land mask every ${mc} NM; highest ground ${top.toFixed(0)} m. */\n`;
  out += `  ${area.id.toLowerCase()}: ${JSON.stringify({ e0: +e0.toFixed(4), n0: +n0.toFixed(4), cellNm: CELL_NM, cols, rows, maskScale: MASK_SCALE })
    .slice(0, -1)}, h: "${packed.h}", m: "${packed.m}" },\n`;
}
out += "};\n";
const target = path.join(root, "src", "engine", "real-terrain.ts");
writeFileSync(target, out);
console.log(`Written ${target} (${(out.length / 1024).toFixed(0)} KB)`);
