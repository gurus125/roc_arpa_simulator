// Makes src/engine/real-depths.ts: approximate water depths for the real areas.
//
// Needs, once (not needed to build or run the simulator): the ETOPO 2022 15 arc-second grid of
// each area, as the JSON that NOAA's ERDDAP server gives. For each area of scripts/areas.mjs, open
//   https://coastwatch.pfeg.noaa.gov/erddap/griddap/ETOPO_2022_v1_15s.json?z[(SOUTH):1:(NORTH)][(WEST):1:(EAST)]
// with SOUTH, NORTH, WEST and EAST the area's box (for Goa: z[(15.0):1:(15.8)][(73.35):1:(74.15)])
// and save it as <id>.json (goa.json, kochi.json, kutch.json, mumbai.json) in one folder. Then:
//   node scripts/make-depths.mjs <folder>
//
// Depths: ETOPO 2022 15 Arc-Second Global Relief Model, NOAA National Centers for Environmental
// Information, doi:10.25921/fd45-gt74 (its ocean depths come largely from GEBCO). Free to use with
// this credit. Cells of about 450 m: shoals, banks and dredged channels smaller than that are not in
// it, and near the coast it is not reliable. Heights are above the EGM2008 geoid (about mean sea
// level), not chart datum, and there is no tide. NOT A CHART AND NOT FOR NAVIGATION.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { build } from "esbuild";
import { AREAS, toLocal, toLatLon } from "./areas.mjs";

/** Spacing of the depth nodes, NM: the source's own spacing in latitude (15 seconds = 0.25'). */
const CELL_NM = 0.25;

const [folder] = process.argv.slice(2);
if (!folder) {
  console.error("Give the folder of <id>.json files (see the top of this file).");
  process.exit(1);
}
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
// The packing is the simulator's own (src/engine/depth.ts), so the two cannot drift apart.
const bundled = await build({ entryPoints: [path.join(root, "src", "engine", "depth.ts")], bundle: true, format: "esm", platform: "node", write: false });
const { packDepths, unpackDepths } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString("base64")}`);

/** An ERDDAP griddap JSON file as a regular grid: latitudes south to north, longitudes west to east, z in metres (up). */
function readGrid(file) {
  const t = JSON.parse(readFileSync(file, "utf8")).table;
  const iLat = t.columnNames.indexOf("latitude"), iLon = t.columnNames.indexOf("longitude"), iZ = t.columnNames.indexOf("z");
  if (iLat < 0 || iLon < 0 || iZ < 0) throw new Error(`${file}: expected the columns latitude, longitude and z`);
  const lats = [...new Set(t.rows.map((r) => r[iLat]))].sort((a, b) => a - b);
  const lons = [...new Set(t.rows.map((r) => r[iLon]))].sort((a, b) => a - b);
  const z = new Float64Array(lats.length * lons.length).fill(NaN);
  const li = new Map(lats.map((v, k) => [v, k])), lo = new Map(lons.map((v, k) => [v, k]));
  for (const r of t.rows) z[li.get(r[iLat]) * lons.length + lo.get(r[iLon])] = r[iZ] === null ? NaN : r[iZ];
  const missing = z.filter((v) => !Number.isFinite(v)).length;
  if (missing) throw new Error(`${file}: ${missing} cells have no value`);
  return { lat0: lats[0], dLat: (lats[lats.length - 1] - lats[0]) / (lats.length - 1), nLat: lats.length, lon0: lons[0], dLon: (lons[lons.length - 1] - lons[0]) / (lons.length - 1), nLon: lons.length, z };
}

/** The source's height at a latitude and longitude: bilinear between the four nearest cells, held at the edge outside it. */
function zAt(g, lat, lon) {
  const fi = Math.min(g.nLat - 1, Math.max(0, (lat - g.lat0) / g.dLat));
  const fj = Math.min(g.nLon - 1, Math.max(0, (lon - g.lon0) / g.dLon));
  const i = Math.min(g.nLat - 2, Math.floor(fi)), j = Math.min(g.nLon - 2, Math.floor(fj));
  const a = fi - i, b = fj - j;
  const v = (p, q) => g.z[p * g.nLon + q];
  return (1 - a) * ((1 - b) * v(i, j) + b * v(i, j + 1)) + a * ((1 - b) * v(i + 1, j) + b * v(i + 1, j + 1));
}

let out = `// GENERATED by scripts/make-depths.mjs. Do not edit by hand.
// Depths: ETOPO 2022 15 Arc-Second Global Relief Model, NOAA National Centers for Environmental
// Information, doi:10.25921/fd45-gt74 (ocean depths largely from GEBCO). Resampled here to the
// scenario frame. Approximate depths below mean sea level, in whole metres, 0 on land: cells of about
// 450 m, not reliable near the coast, not chart datum, no tide. NOT A CHART AND NOT FOR NAVIGATION.
import { PackedDepths } from "./depth";

export const REAL_DEPTHS_CREDIT =
  "Depths: ETOPO 2022 15 Arc-Second Global Relief Model, NOAA National Centers for Environmental Information, doi:10.25921/fd45-gt74. Approximate, about 450 m cells, below mean sea level: not a chart and not for navigation.";

export const REAL_DEPTHS: Record<string, PackedDepths> = {
`;
for (const area of AREAS) {
  const id = area.id.toLowerCase();
  const file = path.join(folder, `${id}.json`);
  if (!existsSync(file)) {
    console.log(`${area.title}: no ${id}.json, left out`);
    continue;
  }
  const src = readGrid(file);
  const o = area.origin;
  const b = area.box;
  // The same frame as the terrain (scripts/make-terrain.mjs): the box's corners, east and north of the origin.
  const corners = [[b.south, b.west], [b.south, b.east], [b.north, b.west], [b.north, b.east]].map(([la, lo]) => toLocal(o, la, lo));
  const e0 = Math.min(...corners.map((c) => c.e));
  const e1 = Math.max(...corners.map((c) => c.e));
  const n0 = (b.south - o.lat) * 60;
  const n1 = (b.north - o.lat) * 60;
  const cols = Math.floor((e1 - e0) / CELL_NM) + 1;
  const rows = Math.floor((n1 - n0) / CELL_NM) + 1;
  const depths = new Float32Array(cols * rows);
  let deepest = 0;
  let sea = 0;
  for (let j = 0; j < rows; j++) {
    for (let i = 0; i < cols; i++) {
      const ll = toLatLon(o, e0 + i * CELL_NM, n0 + j * CELL_NM);
      const d = Math.max(0, Math.round(-zAt(src, ll.lat, ll.lon)));
      depths[j * cols + i] = d;
      if (d > 0) sea++;
      deepest = Math.max(deepest, d);
    }
  }
  const grid = { e0: +e0.toFixed(4), n0: +n0.toFixed(4), cellNm: CELL_NM, cols, rows, depths };
  const packed = packDepths(grid);
  // Check: what is unpacked is what was packed.
  const back = unpackDepths(packed);
  for (let q = 0; q < depths.length; q++) if (back.depths[q] !== depths[q]) throw new Error(`depth ${q} did not survive packing`);
  console.log(`${area.title}: ${cols} x ${rows} depths (source ${src.nLat} x ${src.nLon}), ${((100 * sea) / depths.length).toFixed(0)}% water, deepest ${deepest} m, ${(packed.d.length / 1024).toFixed(0)} KB packed`);
  out += `  /** ${area.title}: ${cols} x ${rows} depths every ${CELL_NM} NM; deepest ${deepest} m. */\n`;
  out += `  ${id}: ${JSON.stringify({ e0: grid.e0, n0: grid.n0, cellNm: CELL_NM, cols, rows }).slice(0, -1)}, d: "${packed.d}" },\n`;
}
out += "};\n";
const target = path.join(root, "src", "engine", "real-depths.ts");
writeFileSync(target, out);
console.log(`Written ${target} (${(out.length / 1024).toFixed(0)} KB)`);
